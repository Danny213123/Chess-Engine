bool kpk_is_win(Color stm, Square wksq, Square bksq, Square psq) {
    int idx = kpk_index_impl(stm, wksq, bksq, psq);
    if (idx < 0 || idx >= 196608) return false;
    return (KPK_BITBASE[idx >> 3] >> (idx & 7)) & 1;
}

bool has_opposition(const Board& b, Color side) {
    // Direct opposition: kings on the same file or rank with exactly 1 square
    // between them (Chebyshev distance = 2, same file OR same rank),
    // AND it is the OTHER side's turn to move.
    // Also covers: same diagonal with 1 intermediate square (distance=2, diagonal).
    // Standard definition: kings on same rank or file with 1 square gap AND
    // other side to move = the given side has the opposition.
    if (b.side_to_move == side) return false;  // must be the OTHER side's turn

    Square ksq = b.king_square(side);
    Square opp_ksq = b.king_square(static_cast<Color>(1 - side));

    int df = std::abs(sq_file(ksq) - sq_file(opp_ksq));
    int dr = std::abs(sq_rank(ksq) - sq_rank(opp_ksq));

    // Direct opposition: 1 square apart on same rank or file (Chebyshev=1 → distance 1)
    // Wait: "odd number of squares between" = 1 means they are 2 squares apart (king-distance 2).
    // Wikipedia: "Direct opposition: kings facing each other with one square between them"
    // → kings are 2 squares apart on the same rank or file. df=0, dr=2 OR df=2, dr=0.
    // "Diagonal opposition" is when df==dr==2 (2 squares diagonally apart).
    if (df == 0 && dr == 2) return true;  // same file, 1 square between
    if (df == 2 && dr == 0) return true;  // same rank, 1 square between
    if (df == 2 && dr == 2) return true;  // diagonal opposition (2 diagonally apart)
    return false;
}

bool is_wrong_bishop_rook_pawn_draw(const Board& b) {
    // Pattern: one side has K + B + rook-pawn (a or h file); bishop is the
    // WRONG color for the promotion square; the defending king can reach the
    // promotion corner.
    for (Color attacker = WHITE; attacker <= BLACK; ++attacker) {
        Color defender = static_cast<Color>(1 - attacker);

        // Attacker must have exactly K + B + 1 pawn (the rook pawn), no other pieces
        if (piece_count(b, attacker, BISHOP) != 1) continue;
        if (piece_count(b, attacker, PAWN)   != 1) continue;
        if (piece_count(b, attacker, KNIGHT) != 0) continue;
        if (piece_count(b, attacker, ROOK)   != 0) continue;
        if (piece_count(b, attacker, QUEEN)  != 0) continue;

        // Defender must have only a king (K vs K+B+P)
        if (piece_count(b, defender, PAWN)   != 0) continue;
        if (piece_count(b, defender, KNIGHT) != 0) continue;
        if (piece_count(b, defender, BISHOP) != 0) continue;
        if (piece_count(b, defender, ROOK)   != 0) continue;
        if (piece_count(b, defender, QUEEN)  != 0) continue;

        // Pawn must be a rook pawn (a or h file)
        Bitboard pawn_bb = b.pieces_of(attacker, PAWN);
        Square psq = static_cast<Square>(__builtin_ctzll(pawn_bb));
        int pf = sq_file(psq);
        if (pf != 0 && pf != 7) continue;

        // Promotion square for the attacker
        Square promo_sq;
        if (attacker == WHITE) {
            promo_sq = static_cast<Square>(56 + pf);  // a8 or h8
        } else {
            promo_sq = static_cast<Square>(pf);  // a1 or h1
        }

        // Bishop color and promotion square color
        Bitboard bish_bb = b.pieces_of(attacker, BISHOP);
        Square bsq = static_cast<Square>(__builtin_ctzll(bish_bb));
        bool bishop_light = is_light_square(bsq);
        bool promo_light = is_light_square(promo_sq);

        // Wrong bishop: bishop cannot control the promotion square
        if (bishop_light == promo_light) continue;  // right color — can win

        // Defending king can reach the promotion corner
        Square def_king = b.king_square(defender);
        // Pawn distance to promotion (number of ranks to advance)
        int pawn_rank = sq_rank(psq);
        int promo_rank = sq_rank(promo_sq);
        int pawn_dist = std::abs(promo_rank - pawn_rank);
        // King distance to promotion corner
        int king_dist = chebyshev(def_king, promo_sq);
        // Defender can reach the promotion corner in time?
        // Canonical check: king_dist <= pawn_dist + 1 (with side to move adjustment)
        int extra = (b.side_to_move == defender) ? 0 : 1;
        if (king_dist <= pawn_dist + extra) {
            return true;
        }
    }
    return false;
}

bool is_fortress(const Board& b) {
    // Conservative pattern set (ENDG-05, D-11):
    // Only returns true for CANONICALLY recognized fortress positions.
    if (is_fortress_kb_vs_krp(b)) return true;
    if (is_fortress_kn_vs_kp(b))  return true;
    if (is_fortress_locked_pawns(b)) return true;
    return false;
}

void endgame_eval(const Board& b, int& mg, int& eg, int phase, bool fortress_enabled) {
    // ---- Fortress detection (ENDG-05) — default OFF per D-11 ---------------
    // Bypassed completely when fortress_enabled = false (zero cost path).
    if (fortress_enabled && is_fortress(b)) {
        mg = v7::coeffs::fortress_score;
        eg = v7::coeffs::fortress_score;
        return;  // short-circuit: known draw
    }

    // ---- Wrong-bishop + rook-pawn draw (ENDG-03) ----------------------------
    if (is_wrong_bishop_rook_pawn_draw(b)) {
        // Scale eg toward DRAW using wrong_bishop_rp_scale.
        // Scale = 0: full draw (multiply by 0); Scale = 256: no change.
        eg = (eg * v7::coeffs::wrong_bishop_rp_scale) / 256;
        mg = (mg * v7::coeffs::wrong_bishop_rp_scale) / 256;
        return;
    }

    // ---- KPK probe (ENDG-01) ------------------------------------------------
    // Detect KPK material signature: one side has K+P, other has only K.
    for (Color stronger = WHITE; stronger <= BLACK; ++stronger) {
        Color weaker = static_cast<Color>(1 - stronger);
        if (piece_count(b, stronger, PAWN)   != 1) continue;
        if (piece_count(b, stronger, KNIGHT) != 0) continue;
        if (piece_count(b, stronger, BISHOP) != 0) continue;
        if (piece_count(b, stronger, ROOK)   != 0) continue;
        if (piece_count(b, stronger, QUEEN)  != 0) continue;
        if (piece_count(b, weaker, PAWN)     != 0) continue;
        if (piece_count(b, weaker, KNIGHT)   != 0) continue;
        if (piece_count(b, weaker, BISHOP)   != 0) continue;
        if (piece_count(b, weaker, ROOK)     != 0) continue;
        if (piece_count(b, weaker, QUEEN)    != 0) continue;

        // Pure KPK position found
        Square wksq = b.king_square(stronger);
        Square bksq = b.king_square(weaker);
        Bitboard pawn_bb = b.pieces_of(stronger, PAWN);
        Square psq = static_cast<Square>(__builtin_ctzll(pawn_bb));

        // Normalize: kpk_is_win expects white = the side with the pawn
        // If stronger == BLACK, flip everything for the KPK lookup
        Color stm = b.side_to_move;
        bool is_win;
        if (stronger == WHITE) {
            is_win = kpk_is_win(stm, wksq, bksq, psq);
        } else {
            // Flip colors: "white" = stronger (BLACK side), flip stm
            Color flipped_stm = static_cast<Color>(1 - stm);
            // In the KPK table, WHITE always has the pawn.
            // bksq becomes wksq for the flipped query.
            is_win = kpk_is_win(flipped_stm, bksq, wksq, psq);
        }

        if (!is_win) {
            // Known draw: zero out both scores
            mg = 0;
            eg = 0;
        } else {
            // Known win: assign a large endgame score for the stronger side
            // Use a 5-pawn equivalent as the KPK winning bonus (tunable).
            constexpr int KPK_WIN_SCORE = 500;  // cp
            int sign = (stronger == b.side_to_move) ? 1 : -1;
            eg = sign * KPK_WIN_SCORE;
            mg = sign * KPK_WIN_SCORE;
        }
        return;
    }

    // ---- Opposition eval (ENDG-02) ------------------------------------------
    // Apply opposition_value bonus for the side that has the opposition.
    // Only meaningful in endgame positions (phase < 64 = roughly below 25% midgame).
    if (phase < 64) {
        for (Color side = WHITE; side <= BLACK; ++side) {
            if (has_opposition(b, side)) {
                int bonus = v7::coeffs::opposition_value;
                int sign = (side == WHITE) ? 1 : -1;
                // Apply primarily to the endgame score where it matters most.
                eg += sign * bonus;
                break;
            }
        }
    }
}

