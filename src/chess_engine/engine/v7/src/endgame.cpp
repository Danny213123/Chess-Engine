// Count pieces of given type for given color.
inline int piece_count(const Board& b, Color c, Piece p) {
    return __builtin_popcountll(b.pieces_of(c, p));
}

// Is the bishop on a light square? Light squares = file+rank is even.
inline bool is_light_square(Square sq) {
    return ((sq_file(sq) + sq_rank(sq)) & 1) == 0;
}

// =============================================================================
// Fortress detection helpers (ENDG-05)
// =============================================================================
//
// Conservative set of well-known fortress patterns. Implements ≥2 canonical
// patterns per D-11. Returns true only for positions that are
// CANONICALLY recognized as drawn fortresses.
//
// Pattern 1: K+B vs K+R+P — bishop controls promotion square, rook/pawn
//   cannot make progress. Simplified: check if the weaker side has K+B and
//   the stronger side has K+R+P, and the bishop covers the promotion square.
//
// Pattern 2: K+N vs K+P — knight on a blockading square with king support,
//   defending king within reach of the pawn. Simplified: stalemate-like
//   fortress where the knight permanently blocks.
//
// Pattern 3: Locked pawn chains — identical pawn structures for both sides
//   with no breakthrough possible (symmetric or near-symmetric pawn masses
//   with no passed pawns on either side). Very conservative filter.

static bool is_fortress_kb_vs_krp(const Board& b) {
    // One side has K+B (only), other side has K+R+P (only).
    // Simplified: detect the K+B side, check if bishop controls promotion sq.
    for (Color weak = WHITE; weak <= BLACK; ++weak) {
        Color strong = static_cast<Color>(1 - weak);
        // Weak side: exactly K+B (no pawns, no rooks, no queens)
        if (piece_count(b, weak, BISHOP) != 1) continue;
        if (piece_count(b, weak, ROOK)   != 0) continue;
        if (piece_count(b, weak, QUEEN)  != 0) continue;
        if (piece_count(b, weak, PAWN)   != 0) continue;
        if (piece_count(b, weak, KNIGHT) != 0) continue;
        // Strong side: exactly K+R+P
        if (piece_count(b, strong, ROOK)  != 1) continue;
        if (piece_count(b, strong, PAWN)  != 1) continue;
        if (piece_count(b, strong, QUEEN) != 0) continue;
        if (piece_count(b, strong, BISHOP)!= 0) continue;
        if (piece_count(b, strong, KNIGHT)!= 0) continue;

        // Check if the pawn is a rook pawn (a or h file)
        Bitboard pawn_bb = b.pieces_of(strong, PAWN);
        Square psq = static_cast<Square>(__builtin_ctzll(pawn_bb));
        int pf = sq_file(psq);
        if (pf != 0 && pf != 7) continue;  // must be a/h-file rook pawn

        // Promotion square for strong side's pawn
        Square promo_sq;
        if (strong == WHITE) {
            promo_sq = static_cast<Square>(56 + pf);  // a8 or h8
        } else {
            promo_sq = static_cast<Square>(pf);  // a1 or h1
        }

        // Check bishop color matches promotion square
        Bitboard bish_bb = b.pieces_of(weak, BISHOP);
        Square bsq = static_cast<Square>(__builtin_ctzll(bish_bb));
        bool bishop_light = is_light_square(bsq);
        bool promo_light = is_light_square(promo_sq);

        // For K+B to hold as fortress: bishop controls promotion square
        // (same color as promotion square is required for the fortress to hold)
        if (bishop_light != promo_light) continue;

        // Weak king within reach of the promotion corner
        Square wk_sq = b.king_square(weak);
        if (chebyshev(wk_sq, promo_sq) <= 2) {
            return true;
        }
    }
    return false;
}

static bool is_fortress_kn_vs_kp(const Board& b) {
    // One side has K+N (only), other side has K+P (only).
    // Simplified fortress: knight permanently blocks the passed pawn.
    for (Color blocker = WHITE; blocker <= BLACK; ++blocker) {
        Color pusher = static_cast<Color>(1 - blocker);
        if (piece_count(b, blocker, KNIGHT) != 1) continue;
        if (piece_count(b, blocker, PAWN)   != 0) continue;
        if (piece_count(b, blocker, BISHOP) != 0) continue;
        if (piece_count(b, blocker, ROOK)   != 0) continue;
        if (piece_count(b, blocker, QUEEN)  != 0) continue;
        if (piece_count(b, pusher, PAWN)    != 1) continue;
        if (piece_count(b, pusher, KNIGHT)  != 0) continue;
        if (piece_count(b, pusher, BISHOP)  != 0) continue;
        if (piece_count(b, pusher, ROOK)    != 0) continue;
        if (piece_count(b, pusher, QUEEN)   != 0) continue;

        Bitboard pawn_bb = b.pieces_of(pusher, PAWN);
        Square psq = static_cast<Square>(__builtin_ctzll(pawn_bb));
        Bitboard knight_bb = b.pieces_of(blocker, KNIGHT);
        Square nsq = static_cast<Square>(__builtin_ctzll(knight_bb));

        // Knight directly in front of the pawn?
        Square in_front = (pusher == WHITE)
            ? static_cast<Square>(static_cast<int>(psq) + 8)
            : static_cast<Square>(static_cast<int>(psq) - 8);
        if (nsq != in_front) continue;

        // Blocker king within 2 squares of the knight to support it
        Square bk = b.king_square(blocker);
        if (chebyshev(bk, nsq) <= 2) {
            return true;
        }
    }
    return false;
}

static bool is_fortress_locked_pawns(const Board& b) {
    // Very conservative: both sides have identical pawn structure locked
    // head-to-head (each pawn faces an opposing pawn), no queens, no rooks.
    // This is a draw in practice but not always forced — flag conservatively.
    if (piece_count(b, WHITE, QUEEN) != 0) return false;
    if (piece_count(b, BLACK, QUEEN) != 0) return false;
    if (piece_count(b, WHITE, ROOK)  != 0) return false;
    if (piece_count(b, BLACK, ROOK)  != 0) return false;
    if (piece_count(b, WHITE, BISHOP)!= 0) return false;
    if (piece_count(b, BLACK, BISHOP)!= 0) return false;
    if (piece_count(b, WHITE, KNIGHT)!= 0) return false;
    if (piece_count(b, BLACK, KNIGHT)!= 0) return false;

    // Must have at least one pawn each
    Bitboard wp = b.pieces_of(WHITE, PAWN);
    Bitboard bp = b.pieces_of(BLACK, PAWN);
    if (!wp || !bp) return false;

    // Every white pawn must have a black pawn directly in front (locked chain)
    Bitboard wp_scan = wp;
    while (wp_scan) {
        int s = __builtin_ctzll(wp_scan);
        wp_scan &= wp_scan - 1;
        // Square directly in front for white pawn
        int front = s + 8;
        if (front > 63) return false;
        if (!(bp & (1ULL << front))) return false;
    }
    // Same check for black
    Bitboard bp_scan = bp;
    while (bp_scan) {
        int s = __builtin_ctzll(bp_scan);
        bp_scan &= bp_scan - 1;
        int front = s - 8;
        if (front < 0) return false;
        if (!(wp & (1ULL << front))) return false;
    }
    return true;
}

