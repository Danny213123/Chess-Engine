// =============================================================================
// Square / geometry helpers (local to this TU)
// =============================================================================

inline int sq_file(Square sq) { return static_cast<int>(sq) & 7; }
inline int sq_rank(Square sq) { return static_cast<int>(sq) >> 3; }

// Chebyshev distance between two squares (maximum of file and rank delta).
inline int chebyshev(Square a, Square b) {
    return std::max(std::abs(sq_file(a) - sq_file(b)),
                    std::abs(sq_rank(a) - sq_rank(b)));
}

// Manhattan distance.
inline int manhattan(Square a, Square b) {
    return std::abs(sq_file(a) - sq_file(b)) + std::abs(sq_rank(a) - sq_rank(b));
}

// Mirror square horizontally (flip file within the same rank).
inline Square mirror_sq_h(Square sq) {
    return static_cast<Square>(static_cast<int>(sq) ^ 7);
}

// =============================================================================
// KPK index formula (Stockfish-style, RESEARCH.md Pitfall 5)
// =============================================================================
//
// Symmetry fold: if the pawn is on the right half of the board (file >= 4),
// mirror all three pieces horizontally so the pawn is always on files a-d.
// psq_idx = (rank_of(psq_norm) - 2) * 4 + file_of(psq_norm)  // 0..23
// index = stm | (bksq_norm << 1) | (wksq_norm << 7) | (psq_idx << 13)
//
// This produces indices in [0, 196608) — the KPK_BITBASE array has 24576
// bytes = 196608 bits. Illegal / out-of-range indices map to 0 (DRAW).

static inline int kpk_index_impl(Color stm, Square wksq, Square bksq, Square psq) {
    int pf = sq_file(psq);
    Square wk = wksq, bk = bksq, ps = psq;
    if (pf >= 4) {
        wk = mirror_sq_h(wk);
        bk = mirror_sq_h(bk);
        ps = mirror_sq_h(ps);
    }
    int pr = sq_rank(ps);
    int pf_n = sq_file(ps);
    int psq_idx = (pr - 2) * 4 + pf_n;  // rank 2-7, file 0-3 → index 0..23
    return static_cast<int>(stm) | (static_cast<int>(bk) << 1)
           | (static_cast<int>(wk) << 7) | (psq_idx << 13);
}

